// TestHash2BKnownAnswer is a deterministic known-answer test for the R6
// Algorithm 2.B hardened hash, independent of qpdf's random salts. The
// validation salt below (last byte 0x20) is chosen so the hash loop stops
// exactly on the termination boundary: a pre-fix off-by-one ran one extra
// round here and produced the wrong digest. The expected values were produced
// by an independent reference implementation cross-checked against qpdf
// (libqpdf 12.4.2) output.
func TestHash2BKnownAnswer(t *testing.T) {
	h := &Handler{R: 6}
	// password "userpw", 8-byte validation salt 00 00 00 00 00 00 00 20.
	salt := []byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20}
	want := []byte{
		0x0e, 0xcf, 0x7b, 0x80, 0x78, 0x92, 0xb3, 0x1a, 0x69, 0x36, 0x3f, 0xff, 0x18, 0xc1, 0x9e, 0x4d,
		0x82, 0x51, 0x95, 0xa9, 0x62, 0x68, 0x75, 0xda, 0x2f, 0x1a, 0x0c, 0xd7, 0x52, 0x4e, 0x25, 0x59,
	}
	got := h.hash2B([]byte("userpw"), salt, nil)
	if !bytes.Equal(got, want) {
		t.Fatalf("hash2B mismatch:\n got %x\nwant %x", got, want)
	}
}

// TestVerifyR6KnownVector verifies a full R6 (AES-256) handler whose fields
// were generated deterministically (fixed file key 00..1f, fixed salts) by the
// qpdf-cross-checked reference. The user validation salt triggers the
// Algorithm 2.B termination-boundary case, so this fails on the pre-fix
// key-derivation off-by-one and passes once it is corrected.
func TestVerifyR6KnownVector(t *testing.T) {
	wantKey := []byte{
		0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
		0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
	}
	h := &Handler{
		V: 5, R: 6, Length: 32, Cipher: CipherAESV3, EncryptMetadata: true,
		U: []byte{
			0x0e, 0xcf, 0x7b, 0x80, 0x78, 0x92, 0xb3, 0x1a, 0x69, 0x36, 0x3f, 0xff, 0x18, 0xc1, 0x9e, 0x4d,
			0x82, 0x51, 0x95, 0xa9, 0x62, 0x68, 0x75, 0xda, 0x2f, 0x1a, 0x0c, 0xd7, 0x52, 0x4e, 0x25, 0x59,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20, 0x4b, 0x45, 0x59, 0x53, 0x41, 0x4c, 0x54, 0x30,
		},
		UE: []byte{
			0x1f, 0x49, 0x9f, 0x64, 0x54, 0x31, 0xa6, 0xbd, 0xc2, 0xd5, 0x74, 0xa8, 0x96, 0xe1, 0xa9, 0x44,
			0xcb, 0xd1, 0x11, 0x4e, 0xd8, 0xc7, 0x6b, 0x11, 0xcf, 0x63, 0x33, 0x2f, 0xc5, 0x33, 0xba, 0x2b,
		},
		O: []byte{
			0xe0, 0xe5, 0x83, 0x4a, 0x7d, 0x13, 0x39, 0x18, 0xb1, 0x4e, 0xa2, 0x91, 0x22, 0xd3, 0x2f, 0xb1,
			0x0d, 0xe9, 0xf6, 0x96, 0xc2, 0x24, 0x23, 0x52, 0xd1, 0xb5, 0xa0, 0xda, 0x14, 0x5f, 0xde, 0x17,
			0x4f, 0x56, 0x41, 0x4c, 0x53, 0x41, 0x4c, 0x30, 0x4f, 0x4b, 0x45, 0x59, 0x53, 0x41, 0x4c, 0x30,
		},
		OE: []byte{
			0xfa, 0xbb, 0x59, 0x85, 0x25, 0x5b, 0xfc, 0x81, 0xaa, 0x76, 0xde, 0x04, 0x88, 0x99, 0x8e, 0xdd,
			0x77, 0xb2, 0x92, 0x94, 0x7c, 0xe9, 0x9d, 0xd2, 0x9e, 0xbd, 0xc5, 0x33, 0x66, 0xe2, 0xa3, 0xb4,
		},
	}

	okU, keyU := h.VerifyUser([]byte("userpw"))
	if !okU {
		t.Fatal("VerifyUser(userpw) = false")
	}
	if !bytes.Equal(keyU, wantKey) {
		t.Fatalf("user file key mismatch:\n got %x\nwant %x", keyU, wantKey)
	}

	okO, keyO := h.VerifyOwner([]byte("ownerpw"))
	if !okO {
		t.Fatal("VerifyOwner(ownerpw) = false")
	}
	if !bytes.Equal(keyO, wantKey) {
		t.Fatalf("owner file key mismatch:\n got %x\nwant %x", keyO, wantKey)
	}

	if ok, _ := h.VerifyUser([]byte("wrong")); ok {
		t.Fatal("VerifyUser(wrong) = true")
	}
	if ok, _ := h.VerifyOwner([]byte("wrong")); ok {
		t.Fatal("VerifyOwner(wrong) = true")
	}
}
